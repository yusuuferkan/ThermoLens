export const DICTIONARIES: Record<Lang, Strings> = { en, tr };

export function translate(lang: Lang, key: keyof Strings): string {
  return DICTIONARIES[lang][key] ?? en[key];
}

/** Hook returning a translator bound to the current language. */
export function useT() {
  const lang = useSettings((s) => s.language);
  return (key: keyof Strings) => translate(lang, key);
}
